/**
 * Return a character-specific Korean + Chinese reply.
 * Returns undefined when no keyword matches, so existing
 * scripted story replies can continue normally.
 */
export function keywordReply(
  thread: string,
  text: string,
): string | undefined {
  const character = aliasMap.get(normalize(thread));
  if (!character || !text?.trim()) return undefined;

  const input = normalize(text);
  const candidates = makeCandidates(character, input);

  if (!candidates.length) return undefined;

  candidates.sort((a, b) =>
    b.score - a.score || a.order - b.order
  );

  return candidates[0].reply;
}

/** Optional helper for debugging and story editor previews. */
export function hasKeywordReply(
  thread: string,
  text: string,
): boolean {
  return keywordReply(thread, text) !== undefined;
}

/** Optional helper to preview how many topics each character supports. */
export function getKeywordTopics(thread: string): string[] {
  const character = aliasMap.get(normalize(thread));
  if (!character) return [];

  return Object.keys(voices[character]).filter(
    (topic) => Boolean(voices[character][topic as Topic]),
  );
}
